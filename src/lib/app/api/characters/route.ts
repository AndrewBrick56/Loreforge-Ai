import { NextResponse } from "next/server";
import { z } from "zod";
import { randomUUID } from "crypto";
import { isErrorResponse, requireUser } from "@/lib/auth";
import { sniffImageType } from "@/lib/validate-image";
import { verifyImageToken } from "@/lib/generation-token";
import { downloadFromStorage, imagePath, moveImage, removeFromStorage, uploadImage, type ImageExt } from "@/lib/storage";
import { ART_STYLE_VALUES, ASPECT_RATIO_VALUES, loreSchema } from "@/lib/schemas";
import { IMAGE_MODEL } from "@/lib/openai/generate-character-image";

export const runtime = "nodejs";

// Matches /api/generate's cap — see that route for why 3MB (serverless
// response/request body size limits on hosts like Vercel).
const MAX_BYTES = 3 * 1024 * 1024;
const PNG_PREFIX = "data:image/png;base64,";
const PENDING_PATH_RE = /^pending\/[0-9a-f-]{36}\.png$/;

const bodySchema = z
  .object({
    // Preferred path: the image already lives in Storage (written by
    // /api/generate) and we just finalize/move it — no multi-MB payload in
    // this request at all. imageDataUrl is kept as a fallback for when
    // Storage wasn't available at generate time.
    pendingImagePath: z.string().regex(PENDING_PATH_RE).optional(),
    imageDataUrl: z.string().startsWith(PNG_PREFIX).max(6_000_000).optional(),
    imageToken: z.string().min(10).max(200),
    // The user's original uploaded photo, stored separately from the
    // generated character image. Optional so scene-only saves and old
    // clients don't break; a generic "image/*;base64," prefix is accepted
    // since the source photo can be png/jpeg/webp (unlike the always-png
    // generated result). Capped at the same size as a regular upload.
    sourceImageDataUrl: z.string().max(4_300_000).optional(),
    name: z.string().trim().max(80).optional(),
    style: z.enum(ART_STYLE_VALUES),
    prompt: z.string().max(2000).default(""),
    aspectRatio: z.enum(ASPECT_RATIO_VALUES),
    lore: loreSchema.optional(),
  })
  .refine((v) => Boolean(v.pendingImagePath || v.imageDataUrl), {
    message: "No generated image to save — generate a character first.",
  });

/** Save a freshly generated image (plus its optional source photo) as a new character in the signed-in user's collection. */
export async function POST(req: Request) {
  const auth = await requireUser({ needsServiceRole: true });
  if (isErrorResponse(auth)) return auth;
  const { supabase, user } = auth;

  let body: z.infer<typeof bodySchema>;
  try {
    body = bodySchema.parse(await req.json());
  } catch {
    return NextResponse.json({ error: "That save request looked malformed.", code: "BAD_REQUEST" }, { status: 400 });
  }

  const characterId = randomUUID();
  const imageId = randomUUID();
  const finalPath = imagePath(user.id, characterId, imageId, "png");
  const name = body.name?.trim() || "Untitled Character";

  const uploadedPaths: string[] = [];
  let pendingSourceToClean: string | null = null;

  if (body.pendingImagePath) {
    // The image already exists in Storage — verify it (download + check the
    // signed token against its actual bytes) and move it into place. No
    // large payload travels through this request either way.
    let bytes: Buffer;
    try {
      bytes = await downloadFromStorage(body.pendingImagePath);
    } catch {
      return NextResponse.json(
        { error: "That generated image has expired or was already saved. Please generate it again.", code: "PENDING_NOT_FOUND" },
        { status: 400 }
      );
    }
    if (bytes.byteLength === 0 || bytes.byteLength > MAX_BYTES || sniffImageType(bytes) !== "image/png") {
      return NextResponse.json({ error: "That isn't a valid generated image.", code: "BAD_IMAGE" }, { status: 400 });
    }
    if (!verifyImageToken(bytes, body.imageToken)) {
      return NextResponse.json(
        { error: "Only images generated by LoreForge can be saved. Please generate the image again.", code: "UNVERIFIED_IMAGE" },
        { status: 400 }
      );
    }
    try {
      await moveImage(body.pendingImagePath, finalPath);
      uploadedPaths.push(finalPath);
    } catch (err) {
      console.error("[LoreForge] Save: moving pending image failed:", err);
      return NextResponse.json({ error: "Couldn't store the image. Please try again.", code: "STORAGE_ERROR" }, { status: 502 });
    }
  } else {
    // Legacy/fallback path: the image arrived inline as base64 (Storage
    // wasn't configured at generate time).
    const bytes = Buffer.from(body.imageDataUrl!.slice(PNG_PREFIX.length), "base64");
    if (bytes.byteLength === 0 || bytes.byteLength > MAX_BYTES || sniffImageType(bytes) !== "image/png") {
      return NextResponse.json({ error: "That isn't a valid generated image.", code: "BAD_IMAGE" }, { status: 400 });
    }
    if (!verifyImageToken(bytes, body.imageToken)) {
      return NextResponse.json(
        { error: "Only images generated by LoreForge can be saved. Please generate the image again.", code: "UNVERIFIED_IMAGE" },
        { status: 400 }
      );
    }
    try {
      await uploadImage(finalPath, bytes, "png");
      uploadedPaths.push(finalPath);
    } catch (err) {
      console.error("[LoreForge] Save: upload failed:", err);
      return NextResponse.json({ error: "Couldn't store the image. Please try again.", code: "STORAGE_ERROR" }, { status: 502 });
    }
  }

  // The source photo has no signed token (it was never generated by us —
  // it's the user's own upload), so it's validated by content-sniffing only.
  let sourceBytes: Buffer | null = null;
  if (body.sourceImageDataUrl) {
    const match = /^data:image\/(png|jpeg|webp);base64,/.exec(body.sourceImageDataUrl);
    if (match) {
      const candidate = Buffer.from(body.sourceImageDataUrl.slice(match[0].length), "base64");
      const sniffed = sniffImageType(candidate);
      if (sniffed && candidate.byteLength > 0 && candidate.byteLength <= MAX_BYTES) {
        sourceBytes = candidate;
      }
    }
    // A malformed/oversized source photo is not fatal to saving the
    // character — it's just quietly skipped rather than failing the whole
    // save over a non-essential attachment.
  }

  const sourceImageId = sourceBytes ? randomUUID() : null;
  const sourceMimeType = sourceBytes ? sniffImageType(sourceBytes) : null;
  const sourceExt: ImageExt | null = sourceMimeType === "image/jpeg" ? "jpg" : sourceMimeType === "image/webp" ? "webp" : sourceMimeType === "image/png" ? "png" : null;
  // Keep the actual file bytes, storage extension, Content-Type and database
  // file_ext consistent; source uploads are not silently mislabeled as PNG.
  const sourcePath = sourceBytes && sourceExt ? imagePath(user.id, characterId, sourceImageId!, sourceExt) : null;

  if (sourceBytes && sourcePath && sourceExt) {
    try {
      await uploadImage(sourcePath, sourceBytes, sourceExt);
      uploadedPaths.push(sourcePath);
    } catch (err) {
      // Non-fatal: the character's main image already saved fine; just
      // proceed without the source photo rather than losing everything.
      console.error("[LoreForge] Save: source photo upload failed (continuing without it):", err);
      pendingSourceToClean = sourcePath;
    }
  }

  const { error } = await supabase.rpc("create_character", {
    p_character_id: characterId,
    p_image_id: imageId,
    p_name: name,
    p_style: body.style,
    p_prompt: body.prompt,
    p_storage_path: finalPath,
    p_aspect_ratio: body.aspectRatio,
    p_model: IMAGE_MODEL,
    p_profile: body.lore ?? null,
    p_source_image_id: pendingSourceToClean ? null : sourceImageId,
    p_source_path: pendingSourceToClean ? null : sourcePath,
    p_source_file_ext: pendingSourceToClean ? "png" : sourceExt ?? "png",
  });

  if (error) {
    // The database write failed, so don't leave orphaned files behind.
    await removeFromStorage(uploadedPaths);
    if (error.message.includes("character_limit_reached")) {
      return NextResponse.json(
        { error: "You've reached the limit of 100 saved characters. Delete one to make room.", code: "LIMIT_REACHED" },
        { status: 409 }
      );
    }
    console.error("[LoreForge] Save: create_character failed:", error.message);
    return NextResponse.json({ error: "Couldn't save your character. Please try again.", code: "DB_ERROR" }, { status: 500 });
  }

  return NextResponse.json({ id: characterId, imageId, name, sourceStored: Boolean(sourceImageId && !pendingSourceToClean) });
}
